export function isLegacyStarterDocument(document) {
    return (
        typeof document.content === "string" &&
        ((document.content.includes(
            "Dokumen ini dipakai sebagai contoh Markdown kompleks",
        ) &&
            document.content.includes("## Checklist Deploy")) ||
            (document.content.includes(
                "Ini contoh dokumen Markdown yang isinya sengaja dibuat familiar",
            ) &&
                document.content.includes("## Contoh Link dan Gambar") &&
                document.content.includes("![Logo Rizam MD]") &&
                !document.content.includes("](/favicon.png)")))
    );
}
